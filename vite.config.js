import { defineConfig } from 'vite'
import { fileURLToPath } from 'node:url'
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'

const UNOFF = fileURLToPath(new URL('./node_modules/@unoff/ui/dist/assets', import.meta.url))

// Unoff UI component tokens for the Yelbolt theme (button, input, card…),
// without the components themselves: their stylesheets also hold the
// components' class rules, which would clash with ours (.card…). Only the
// custom-property blocks of the Yelbolt theme are kept.
const COMPONENTS = ['Button', 'Input', 'card', 'Chip', 'SegmentedControl', 'SemanticMessage',
  'SectionTitle', 'Section', 'Thumbnail', 'Tooltip', 'Message', 'form-item', 'list', 'SimpleItem', 'Bar',
  'styles/texts/texts']
function unoffComponentTokens() {
  const out = fileURLToPath(new URL('./src/styles/unoff-yelbolt-components.generated.css', import.meta.url))
  const generate = () => {
    let css = '/* Generated by vite.config.js from @unoff/ui: Yelbolt component tokens. Do not edit. */\n'
    for (const name of COMPONENTS) {
      const src = readFileSync(`${UNOFF}/${name}.css`, 'utf8')
      const blocks = src.match(/(?::root)?\[data-theme=yelbolt\]\{[^{}]*\}/g) ?? []
      // custom properties only
      for (const b of blocks) if (/^[^{]*\{\s*--/.test(b)) css += `/* ${name} */\n${b}\n`
    }
    mkdirSync(fileURLToPath(new URL('./src/styles', import.meta.url)), { recursive: true })
    writeFileSync(out, css)
  }
  return { name: 'unoff-yelbolt-component-tokens', config: generate }
}

export default defineConfig({
  plugins: [unoffComponentTokens()],
  resolve: {
    // A single three.js instance for the app and the Spline loader
    dedupe: ['three'],
    alias: {
      // Unoff UI design tokens (CSS only; the package exports its React
      // components only, so its stylesheets are reached by path)
      '@unoff-styles': `${UNOFF}/styles`
    }
  },
  build: {
    target: 'es2022', // top-level await (translations are loaded before the page renders)
    chunkSizeWarningLimit: 3000
  }
})
